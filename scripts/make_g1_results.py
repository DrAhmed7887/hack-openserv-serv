#!/usr/bin/env python3
"""Runs the real test suite and the real CLI, then writes docs/G1_RESULTS.md from the actual output.

Run: python3 scripts/make_g1_results.py
Nothing in the report is typed by hand except the fixed headings and the limits section.
"""
import hashlib
import json
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from contract_audit.audit import build_audit  # noqa: E402
from contract_audit.inputs import load_case, load_catalog  # noqa: E402


def clean(text):
    return text.replace(str(ROOT), "<repo>")


def source_digest():
    h = hashlib.sha256()
    for p in sorted(list((ROOT / "src").rglob("*.py")) + list((ROOT / "data").rglob("*.json"))):
        h.update(p.relative_to(ROOT).as_posix().encode())
        h.update(p.read_bytes())
    return h.hexdigest()[:16]


def case_rows():
    catalog = load_catalog(ROOT / "data" / "catalog.json")
    rows, all_ok = [], True
    for case_file in sorted((ROOT / "data" / "cases").glob("*.json")):
        case = load_case(case_file)
        exp = json.loads((ROOT / "data" / "expected" / case_file.name).read_text(encoding="utf-8"))
        a = build_audit(catalog, case)
        actual = {
            "completeness": a["completeness"],
            "obligations": {k: {"disposition": v["disposition"], "receipt_status": v["receipt_status"],
                                "full_support": v["full_support"]} for k, v in a["obligations"].items()},
            "calls": {k: v["status"] for k, v in a["calls"].items()},
            "statements": a["statements"], "report_gaps": a["report_gaps"],
        }
        want = {k: exp[k] for k in actual}
        ok = actual == want
        all_ok &= ok
        disp = ", ".join(f"{k}={v['disposition']}/{v['receipt_status']}" for k, v in sorted(a["obligations"].items()))
        rows.append(f"| `{case['case_id']}` | {disp} | `{a['completeness']}` | {'PASS' if ok else 'FAIL'} |")
    return rows, all_ok


def red_rows():
    rows = []
    for red in sorted((ROOT / "docs" / "red").glob("*.RED.log")):
        lines = red.read_text(encoding="utf-8").splitlines()
        reason = next((l for l in lines if l.startswith("E  ") or l.startswith("FAILED") or "AssertionError" in l), "")
        summary = next((l for l in reversed(lines) if " failed" in l or " error" in l), "")
        green = red.with_name(red.name.replace(".RED.", ".GREEN."))
        gsum = ""
        if green.exists():
            gl = green.read_text(encoding="utf-8").splitlines()
            gsum = next((l for l in reversed(gl) if " passed" in l), "")
        rows.append(f"| `{red.name.split('.')[0]}` | {summary.strip()} | {reason.strip()[:90]} | {gsum.strip()} |")
    return rows


def main():
    pytest = subprocess.run([sys.executable, "-m", "pytest", "-v", "-p", "no:cacheprovider"], cwd=ROOT,
                            capture_output=True, text=True)
    rows, table_ok = case_rows()
    out = [
        "# G1 results: Radiology tool-capability contract audit (synthetic mechanism spike)",
        "",
        "Generated by `python3 scripts/make_g1_results.py` from the real test run and the real validator. "
        "Re-run it after any code or data change.",
        "",
        "**What this shows:** a deterministic offline validator behaves as the pre-written expectations say on 7 fixed synthetic cases.",
        "**What this does not show:** nothing here measures clinical accuracy, a real device, a real tool or SERV. SERV was not run: no account, no key, no call. Physician/operator sign-off on obligations and mappings is pending.",
        "",
        "## Run",
        f"- Python {platform.python_version()}, {platform.system()}",
        f"- Source+data digest (first 16 hex of sha256 over src/ and data/*.json): `{source_digest()}`",
        f"- pytest exit code: **{pytest.returncode}**",
        f"- Case table: **{'all 7 PASS' if table_ok and len(rows) == 7 else 'FAILURES PRESENT'}**",
        "",
        "## Case table (actual validator output vs `data/expected/`, written before the validator)",
        "",
        "| Case | Obligation: disposition/receipt | Completeness | vs expected |",
        "|---|---|---|---|",
        *rows,
        "",
        "Only `c01` reaches `full_support`, and only as a fixture: confirmed catalog entry + valid call + valid mock receipt.",
        "",
        "## RED to GREEN evidence",
        "",
        "Each production behaviour had a failing run saved before it was implemented (`docs/red/*.RED.log`) and a passing run after (`*.GREEN.log`). "
        "RED reasons are mostly a missing module (the first run of each cycle) or the named assertion.",
        "",
        "| Cycle | RED summary | First failure | GREEN summary |",
        "|---|---|---|---|",
        *red_rows(),
        "",
        "Cycle `12_review_findings` came from an independent read-only review by a separate reviewer agent: 8 findings (a weak catalog entry reaching full support, duplicate ids hiding an obligation or a statement, a null receipt id matching an uncited claim, non-object `args`, malformed nested input crashing, a mislabelled SERV status, a non-string quote). "
        "Each was reproduced by a failing test first (one case, `study is list`, already passed because an existing check covered it), then fixed.",
        "",
        "Characterisation tests that pass on first run by design (not RED-first): `tests/test_fixtures_reproducible.py`, "
        "and in `test_capability.py` the guard `test_removing_the_only_confirmed_entry_never_yields_supported`, which protects behaviour added in cycle 1.",
        "",
        "## Full test log (verbatim)",
        "",
        "```",
        clean(pytest.stdout).rstrip(),
        "```",
        "",
    ]
    if pytest.stderr.strip():
        out += ["stderr:", "```", clean(pytest.stderr).rstrip(), "```", ""]
    (ROOT / "docs" / "G1_RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/G1_RESULTS.md; pytest exit", pytest.returncode, "; table_ok", table_ok)
    return 0 if pytest.returncode == 0 and table_ok else 1


if __name__ == "__main__":
    sys.exit(main())
